#!/usr/bin/env bash
# Deploy configs into the invoking user's XDG directories.
set -euo pipefail
_lib="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=common.sh
source "${_lib}/common.sh"

deploy_configs() {
  local cfg="${OPS_ROOT}/configs"
  local fish_dir="${CONFIG_HOME}/fish"

  mkdir -p \
    "$fish_dir/conf.d" \
    "$fish_dir/functions" \
    "${CONFIG_HOME}/tmux" \
    "${CONFIG_HOME}/yazi" \
    "${CONFIG_HOME}/atuin" \
    "${CONFIG_HOME}/mise" \
    "${CONFIG_HOME}/direnv" \
    "${CONFIG_HOME}/git" \
    "${TARGET_HOME}/.local/bin"

  cp -a "${cfg}/fish/config.fish" "${fish_dir}/config.fish"
  cp -a "${cfg}/fish/conf.d/." "${fish_dir}/conf.d/"
  cp -a "${cfg}/fish/functions/." "${fish_dir}/functions/"

  cat >"${fish_dir}/conf.d/99-ops-root.fish" <<EOF
# Generated by ops-workstation install. Do not edit by hand.
set -gx OPS_WORKSTATION_ROOT ${OPS_ROOT}
set -gx OPS_CONFIG_HOME ${CONFIG_HOME}
set -gx RIPGREP_CONFIG_PATH ${CONFIG_HOME}/ripgreprc
fish_add_path -g ${PREFIX_BIN}
fish_add_path -g \$HOME/.local/bin
EOF

  cp -a "${cfg}/starship.toml" "${CONFIG_HOME}/starship.toml"

  cp -a "${cfg}/tmux/tmux.conf" "${CONFIG_HOME}/tmux/tmux.conf"
  local fish_path shell_line
  fish_path="$(command -v fish || true)"
  if [[ -n "$fish_path" ]]; then
    shell_line="set -g default-shell \"${fish_path}\""
  else
    shell_line="# fish no encontrado al instalar"
  fi
  # shellcheck disable=SC2016
  sed "s|# OPS_DEFAULT_SHELL|${shell_line}|" "${CONFIG_HOME}/tmux/tmux.conf" >"${CONFIG_HOME}/tmux/tmux.conf.tmp"
  mv "${CONFIG_HOME}/tmux/tmux.conf.tmp" "${CONFIG_HOME}/tmux/tmux.conf"
  ln -sfn "${CONFIG_HOME}/tmux/tmux.conf" "${TARGET_HOME}/.tmux.conf"

  cp -a "${cfg}/yazi/." "${CONFIG_HOME}/yazi/"
  cp -a "${cfg}/atuin/config.toml" "${CONFIG_HOME}/atuin/config.toml"
  cp -a "${cfg}/mise/config.toml" "${CONFIG_HOME}/mise/config.toml"
  cp -a "${cfg}/direnv/direnvrc" "${CONFIG_HOME}/direnv/direnvrc"
  cp -a "${cfg}/ripgreprc" "${CONFIG_HOME}/ripgreprc"

  if [[ -f "${TARGET_HOME}/.gitconfig" ]]; then
    if ! grep -q 'ops-workstation' "${TARGET_HOME}/.gitconfig" 2>/dev/null; then
      cat "${cfg}/git/delta.gitconfig" >>"${TARGET_HOME}/.gitconfig"
    fi
  else
    cp -a "${cfg}/git/delta.gitconfig" "${TARGET_HOME}/.gitconfig"
  fi

  ln -sfn "${OPS_ROOT}/bin/ops" "${PREFIX_BIN}/ops"
  record_install link ops "${PREFIX_BIN}/ops"
  chmod +x "${OPS_ROOT}/bin/ops" "${OPS_ROOT}/install" "${OPS_ROOT}/rollback" "${OPS_ROOT}/rollback.sh"

  if [[ "${NEED_USER_PATH}" == "1" ]]; then
    ensure_user_path_snippet
  fi

  own \
    "$fish_dir" \
    "${CONFIG_HOME}/starship.toml" \
    "${CONFIG_HOME}/tmux" \
    "${CONFIG_HOME}/yazi" \
    "${CONFIG_HOME}/atuin" \
    "${CONFIG_HOME}/mise" \
    "${CONFIG_HOME}/direnv" \
    "${CONFIG_HOME}/ripgreprc" \
    "${TARGET_HOME}/.gitconfig" \
    "${TARGET_HOME}/.tmux.conf" \
    "${TARGET_HOME}/.local/bin"

  ok "Configs en ${CONFIG_HOME} para ${TARGET_USER}"
}

ensure_user_path_snippet() {
  local line f
  line="export PATH=\"${PREFIX_BIN}:\$PATH\" # ops-workstation"
  for f in .profile .bash_profile .bashrc .zshrc; do
    [[ -f "${TARGET_HOME}/${f}" ]] || continue
    if grep -q 'ops-workstation' "${TARGET_HOME}/${f}"; then
      continue
    fi
    printf '\n%s\n' "$line" >>"${TARGET_HOME}/${f}"
    own "${TARGET_HOME}/${f}"
  done
}

maybe_set_fish_shell() {
  local fish_path now
  fish_path="$(command -v fish || true)"
  if [[ -z "$fish_path" ]]; then
    die "fish no quedó instalado"
  fi
  if ! grep -qxF "$fish_path" /etc/shells 2>/dev/null; then
    printf '%s\n' "$fish_path" >>/etc/shells
  fi
  now="$(getent passwd "$TARGET_USER" | cut -d: -f7)"
  if [[ "$now" == "$fish_path" ]]; then
    ok "Login shell de ${TARGET_USER} ya es fish"
    return 0
  fi
  if [[ "${OPS_SET_FISH:-1}" == "1" ]]; then
    log "Login shell de ${TARGET_USER} → ${fish_path}"
    chsh -s "$fish_path" "$TARGET_USER" || die "chsh falló. Manual: chsh -s ${fish_path} ${TARGET_USER}"
  else
    warn "Login shell no cambiado (--no-fish-shell)"
  fi
}

write_install_manifest() {
  local snap="${CURRENT_SNAPSHOT:?}"
  mkdir -p "$(dirname "$MANIFEST_CURRENT")"
  cat >"$MANIFEST_CURRENT" <<EOF
{
  "snapshot": "$(basename "$snap")",
  "installed_at": "$(date -Iseconds)",
  "ops_root": "${OPS_ROOT}",
  "user": "${TARGET_USER}",
  "pm": "${PM}",
  "os": "${OS_PRETTY}",
  "prefix": "${PREFIX_BIN}"
}
EOF
  cp -a "$MANIFEST_CURRENT" "${snap}/manifest.json"
  own "$OPS_DATA" "$OPS_STATE"
}
